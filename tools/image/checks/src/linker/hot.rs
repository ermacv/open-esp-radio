//! The hot code an image takes: the linker fragment of its `hot` level.
//!
//! A function marked `#[hot(N)]` (`oer-portable-hot`) has its own input
//! section `.hot.<N>.text.<module path>::<name>`. The image names the highest
//! level it takes (`[package.metadata.open-radio] hot`); this fragment gives
//! each level it takes an output section `.hot.<N>.text` in SRAM, after the
//! runtime script's `.hot.text`. The levels it does not take fall into
//! ordinary `.text` by the rule the script places there.

use serde::{Deserialize, Serialize};

/// The fragment the runtime script includes, written beside the image
/// linker's specification before the first link.
pub const FRAGMENT: &str = "hot-text.x";

/// The greatest level, as `oer-portable-hot`'s attribute takes it.
pub const GREATEST_LEVEL: u8 = 3;

/// A hot level an image takes: from 1 to [`GREATEST_LEVEL`].
#[derive(Clone, Copy, Debug, Deserialize, Eq, Ord, PartialEq, PartialOrd, Serialize)]
#[serde(try_from = "u8", into = "u8")]
pub struct Level(u8);

impl TryFrom<u8> for Level {
    type Error = String;

    fn try_from(level: u8) -> Result<Self, Self::Error> {
        if (1..=GREATEST_LEVEL).contains(&level) {
            Ok(Self(level))
        } else {
            Err(format!(
                "a hot level is from 1 to {GREATEST_LEVEL}, not {level}"
            ))
        }
    }
}

impl From<Level> for u8 {
    fn from(level: Level) -> Self {
        level.0
    }
}

/// The fragment of the levels from 1 to `highest`; none, an empty one.
pub fn fragment(highest: Option<Level>) -> String {
    let mut text =
        String::from("/* Generated by the image linker from the image's `hot` level. */\n");
    for level in 1..=highest.map_or(0, u8::from) {
        text.push_str(&format!(
            "  .hot.{level}.text : {{ *(.hot.{level}.text.*); . = ALIGN(4); }} > INTERNAL_LOW\n"
        ));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_image_takes_every_level_up_to_its_own() {
        let fragment = fragment(Some(Level::try_from(2).unwrap()));
        assert!(fragment.contains(
            "  .hot.1.text : { *(.hot.1.text.*); . = ALIGN(4); } > INTERNAL_LOW\n\
             \x20 .hot.2.text : { *(.hot.2.text.*); . = ALIGN(4); } > INTERNAL_LOW\n"
        ));
        assert!(!fragment.contains(".hot.3."));
    }

    #[test]
    fn an_image_without_a_level_takes_none() {
        assert!(!fragment(None).contains(".hot."));
    }

    #[test]
    fn a_level_outside_the_attributes_range_is_refused() {
        for level in [0, GREATEST_LEVEL + 1] {
            assert!(Level::try_from(level).is_err(), "{level}");
        }
        assert_eq!(u8::from(Level::try_from(GREATEST_LEVEL).unwrap()), 3);
    }

    /// The attribute takes the greatest level this module does.
    #[oer_portable_hot::hot(3)]
    fn greatest() {}

    #[test]
    fn the_attribute_takes_the_greatest_level() {
        assert_eq!(GREATEST_LEVEL, 3);
        greatest();
    }
}
