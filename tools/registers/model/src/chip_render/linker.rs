//! The linker fragment of a chip's images: the DMA window from the root's
//! `dma-window` RAM region and the low address bits its narrowest low-bits
//! pointer keeps, so the link refuses DMA storage outside the window or at
//! an address whose kept low bits are zero (the null a low-bits pointer
//! reads).

use std::fmt::Write as _;

use super::Error;
use crate::{chip_model::ChipModel, layouts::DMA_REGION};

const CHECKS: &str = "ASSERT(__runtime_dma_bss_end <= __runtime_dma_data_start ||
       (__runtime_dma_data_start >= DMA_WINDOW_ORIGIN &&
        __runtime_dma_bss_end <= DMA_WINDOW_ORIGIN + DMA_WINDOW_LENGTH),
       \"runtime DMA storage lies outside the DMA window\");
ASSERT(__runtime_dma_bss_end <= __runtime_dma_data_start ||
       ((__runtime_dma_data_start & ((1 << DMA_ADDRESS_LOW_BITS) - 1)) != 0 &&
        (__runtime_dma_data_start >> DMA_ADDRESS_LOW_BITS) ==
        ((__runtime_dma_bss_end - 1) >> DMA_ADDRESS_LOW_BITS)),
       \"runtime DMA storage holds an address with zero low DMA address bits\");
";

/// The `dma-window.x` fragment of `model`'s images.
pub fn dma_window(model: &ChipModel) -> Result<String, Error> {
    let Some(region) = model
        .ram_regions()
        .iter()
        .find(|region| region.name == DMA_REGION)
    else {
        return Ok(String::from(
            "/* @generated by `cargo registers generate` from the chip root; do not edit.\n   \
             The root has no DMA window, so the link refuses any DMA storage. */\n\
             ASSERT(__runtime_dma_bss_end <= __runtime_dma_data_start,\n       \
             \"no DMA window known: this chip's images hold no DMA storage\");\n",
        ));
    };
    let end = region.base.saturating_add(region.size);
    if end > 1 << 32 || region.size == 0 {
        return Err(Error::new(
            &region.name,
            "the DMA window does not fit a 32-bit address",
        ));
    }
    // The narrowest pointer that keeps only low bits of a window address.
    let narrowest = model
        .types()
        .values()
        .flat_map(|block| {
            block.templates.iter().flat_map(move |(key, register)| {
                register.fields.iter().filter_map(move |field| {
                    let pointer = field.pointer.as_ref()?;
                    (pointer.placement == DMA_REGION && pointer.encoding.low_bits).then(|| {
                        (
                            pointer.encoding.width,
                            format!("{}.{key}.{}", block.name(), field.name),
                        )
                    })
                })
            })
        })
        .min();
    let mut output = String::from(
        "/* @generated by `cargo registers generate` from the chip root; do not edit.\n",
    );
    match narrowest {
        Some((width, field)) => {
            let _ = write!(
                output,
                "   The `{DMA_REGION}` RAM region and the low address bits the pointer\n   \
                 {field} keeps: DMA storage lies inside the region and never at an\n   \
                 address whose low DMA_ADDRESS_LOW_BITS bits are zero. */\n\
                 DMA_WINDOW_ORIGIN = 0x{:08x};\n\
                 DMA_WINDOW_LENGTH = 0x{:08x};\n\
                 DMA_ADDRESS_LOW_BITS = {width};\n{CHECKS}",
                region.base, region.size
            );
        }
        None => {
            let _ = write!(
                output,
                "   The `{DMA_REGION}` RAM region: DMA storage lies inside it. */\n\
                 DMA_WINDOW_ORIGIN = 0x{:08x};\n\
                 DMA_WINDOW_LENGTH = 0x{:08x};\n\
                 ASSERT(__runtime_dma_bss_end <= __runtime_dma_data_start ||\n       \
                 (__runtime_dma_data_start >= DMA_WINDOW_ORIGIN &&\n        \
                 __runtime_dma_bss_end <= DMA_WINDOW_ORIGIN + DMA_WINDOW_LENGTH),\n       \
                 \"runtime DMA storage lies outside the DMA window\");\n",
                region.base, region.size
            );
        }
    }
    Ok(output)
}
