//! `cargo registers`: the generated outputs of a chip's register model and
//! the register checks. `generate` renders the thin PAC
//! (`chips/<chip>/pac/src/generated.rs`) and the DMA-window linker fragment
//! (`chips/<chip>/layout/linker/dma-window.x`) from the chip root, its block
//! types, layouts and evidence catalogs and its ownership policy
//! (`chips/<chip>/registers/`).

#![forbid(unsafe_code)]

use std::path::{Path, PathBuf};

use oer_registers_model::Chip;

pub mod checks;
mod host;
pub mod signatures;

pub type Result<T> = std::result::Result<T, Box<dyn std::error::Error + Send + Sync>>;

/// The generated files of `chip` below the checkout `root`.
pub struct Outputs {
    /// The thin PAC's generated module.
    pub pac: PathBuf,
    /// The linker fragment of the chip's images.
    pub linker: PathBuf,
}

impl Outputs {
    pub fn of(root: &Path, chip: &str) -> Self {
        let chip = root.join("chips").join(chip);
        Self {
            pac: chip.join("pac/src/generated.rs"),
            linker: chip.join("layout/linker/dma-window.x"),
        }
    }
}

/// Load `chip`'s model and policy below the checkout `root`, checking every
/// rule of both.
pub fn validate(root: &Path, chip: &str) -> Result<()> {
    let chip = Chip::load(root, chip)?;
    chip.policy()?;
    Ok(())
}

/// Render every output of `chip` and write them, or with `check` compare
/// them with the files as they are. Nothing is written unless every output
/// renders.
pub fn generate(root: &Path, chip: &str, check: bool) -> Result<()> {
    let outputs = Outputs::of(root, chip);
    let loaded = Chip::load(root, chip)?;
    let policy = loaded.policy()?;
    let rust = oer_registers_model::chip_render::render(&loaded.model, &policy)?;
    let pac = host::format(
        &format!(
            "// @generated by `cargo registers generate --chip {chip}` from\n\
             // chips/{chip}/registers; do not edit.\n\n{rust}"
        ),
        "2024",
    )?;
    let linker = oer_registers_model::chip_render::dma_window(&loaded.model)?;
    let pac_path = host::destination(&outputs.pac)?;
    let linker_path = host::destination(&outputs.linker)?;
    host::publish(&[(&pac_path, pac), (&linker_path, linker)], check)
}
