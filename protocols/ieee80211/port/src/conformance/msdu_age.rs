//! Admission age through queued publication, retry and A-MPDU re-formation.
use super::{Environment, Execution, ModelOnlyReason, Report};
use crate::Ieee80211Instant;
use oer_time::Duration;

/// Deterministically controlled age boundary exercised by a fixture.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Case {
    /// Expire before the first publication.
    BeforePublication,
    /// Expire after one failed publication, before the next retry.
    BetweenRetries,
    /// Retain both Sent and unpublished members' ages through re-formation.
    Reformation,
    /// Acknowledgement of a hardware-owned attempt wins over its age.
    HardwareOwned,
}
impl Case {
    /// All admission-age cases.
    pub const ALL: [Self; 4] = [
        Self::BeforePublication,
        Self::BetweenRetries,
        Self::Reformation,
        Self::HardwareOwned,
    ];
    /// A sub-TU duration exercises the typed lifetime without rounding.
    pub const LIFETIME: Duration = Duration::from_micros(100);
    /// The fixture controls age and queue/result holds; physical runs skip it.
    pub const fn execution(self) -> Execution {
        Execution::ModelOnly(ModelOnlyReason::MsduAge)
    }
}
/// Actual terminal classification, excluding backend-specific air evidence.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum End {
    /// The actual transmission completed successfully.
    Delivered,
    /// The terminal names these original subframe positions as expired.
    Expired(u64),
}
/// Observations of actual owners, timestamps, publications and terminals.
pub struct Trace<E> {
    /// Terminals delivered by the backend, in order.
    pub ends: E,
    /// PPDUs actually published, not the number of aggregate subframes.
    pub publications: usize,
    /// Separate expiry counter read after the case.
    pub expired_msdus: u32,
    /// Original admission coordinates, before either re-formation.
    pub admitted: [Ieee80211Instant; 2],
    /// Admission coordinates read back from the retained owners.
    pub returned: [Ieee80211Instant; 2],
    /// Ticket and up to two actual buffer slot identities at admission.
    pub owners: [u8; 3],
    /// The same identities read from terminal owners.
    pub returned_owners: [u8; 3],
    /// BAR frames generated by the backend itself: always zero.
    pub backend_bars: usize,
    /// BAR produced by the core after the re-formation expiry report.
    pub core_bar: Option<CoreBar>,
}
/// The core's response to an expired active BA-window head.
pub struct CoreBar {
    /// The expired head's original sequence number, read from its owner.
    pub head: oer_ieee80211_wire::sequence::SequenceNumber,
    /// Agreement TID.
    pub tid: u8,
    /// Peer and local addresses given to the originator.
    pub addresses: [[u8; 6]; 2],
    /// Actual BAR frame returned by the originator.
    pub frame: [u8; oer_ieee80211_wire::block_ack::BLOCK_ACK_REQUEST_LEN],
}
/// Backend-specific admission and explicit owner-controlled virtual time.
pub trait Harness {
    /// Bounded or allocating storage for the observed terminals.
    type Ends: AsRef<[End]>;
    /// Execute the case, collecting actual observations.
    fn exercise(&mut self, case: Case) -> impl core::future::Future<Output = Trace<Self::Ends>>;
}
/// A mismatch between the admission-age contract and actual observations.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Violation {
    /// The backend returned a wrong terminal or expired the wrong members.
    Terminal,
    /// Publication count, separate counter or backend-generated BAR differs.
    Publication,
    /// A return or re-formation reset a member's age.
    Age,
    /// An admitted ticket or buffer owner was lost or replaced.
    Owners,
    /// The core failed to move the expired BA head with a BAR.
    Bar,
}
/// Verify actual observations; expiry never grants BAR ownership to a backend.
pub fn verify<E: AsRef<[End]>>(case: Case, trace: Trace<E>) -> Result<(), Violation> {
    let expected: &[End] = match case {
        Case::BeforePublication | Case::BetweenRetries => &[End::Expired(1)],
        Case::Reformation => &[End::Delivered, End::Expired(1), End::Expired(1)],
        Case::HardwareOwned => &[End::Delivered],
    };
    if trace.ends.as_ref() != expected {
        return Err(Violation::Terminal);
    }
    let (publications, expired) = match case {
        Case::BeforePublication => (0, 1),
        Case::BetweenRetries => (1, 1),
        Case::Reformation => (1, 2),
        Case::HardwareOwned => (1, 0),
    };
    if trace.publications != publications
        || trace.expired_msdus != expired
        || trace.backend_bars != 0
    {
        return Err(Violation::Publication);
    }
    if trace.admitted != trace.returned {
        return Err(Violation::Age);
    }
    if trace.owners != trace.returned_owners {
        return Err(Violation::Owners);
    }
    match (case, trace.core_bar) {
        (Case::Reformation, Some(bar))
            if bar.frame
                == oer_ieee80211_wire::block_ack::encode_block_ack_request(
                    bar.addresses[0],
                    bar.addresses[1],
                    bar.tid,
                    bar.head.wrapping_add(1),
                ) => {}
        (Case::Reformation, _) | (_, Some(_)) => return Err(Violation::Bar),
        (_, None) => {}
    }
    Ok(())
}
/// Run and verify cases applicable to this fixture's environment.
pub async fn check<H: Harness>(
    harness: &mut H,
    environment: Environment,
) -> Result<Report, (Case, Violation)> {
    let mut report = Report::default();
    for case in Case::ALL {
        if !report.includes(environment, case.execution()) {
            continue;
        }
        verify(case, harness.exercise(case).await).map_err(|why| (case, why))?;
        report.passed();
    }
    Ok(report)
}
