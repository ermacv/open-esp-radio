//! The sources a build generates from the facts, where a person writing them
//! by hand could err: a chip's `LAYOUT` and ROM linker script (its layout
//! crate's build script),
//! and the vector table, the per-line entries, the line → handler defaults
//! and the CPU lines of the interrupt table (the staged runtime's build
//! script). Each generator is a pure function of the facts, so the same facts
//! give the same text.

use alloc::{
    format,
    string::{String, ToString},
    vec::Vec,
};
use core::fmt::Write;

use crate::{Facts, Region, Result, Rom};

/// The linker assignments for exactly the ROM functions in the facts.
/// No vendor script or libc symbols are included implicitly.
pub fn rom_script(rom: &Rom) -> Result<String> {
    rom.validate_functions()?;
    let mut text = String::from(
        "/* Generated by `oer_espressif_facts::generate::rom_script`; edit the ROM facts. */\n",
    );
    for function in &rom.functions {
        let _ = writeln!(
            text,
            "/* {} */\n{} = {:#010x};",
            function.source, function.name, function.address
        );
    }
    Ok(text)
}

/// The chip's stack policy key that sizes the CPU0 task stack of an image
/// whose own policy names no allocation.
pub const DEFAULT_CPU0_TASK_STACK_KEY: &str = "default_cpu0_task_stack_bytes";

/// The default CPU0 task stack of a chip's stack policy
/// (`chips/<id>/platform/stack.toml`): positive, a multiple of the 16-byte
/// stack alignment.
pub fn default_cpu0_task_stack_bytes(policy: &str) -> Result<u32> {
    let table: toml::Table =
        toml::from_str(policy).map_err(|error| format!("the chip's stack policy: {error}"))?;
    let bytes = table
        .get(DEFAULT_CPU0_TASK_STACK_KEY)
        .ok_or_else(|| format!("the chip's stack policy names no `{DEFAULT_CPU0_TASK_STACK_KEY}`"))?
        .as_integer()
        .and_then(|bytes| u32::try_from(bytes).ok())
        .filter(|bytes| *bytes > 0 && bytes % 16 == 0)
        .ok_or_else(|| {
            format!("`{DEFAULT_CPU0_TASK_STACK_KEY}` must be a positive u32, aligned to 16 bytes")
        })?;
    Ok(bytes)
}

fn region(region: Region) -> String {
    format!(
        "oer_espressif_staged_layout::Region::new({:#010x}, {:#010x})",
        region.origin, region.length
    )
}

/// The Rust source of a chip's `LAYOUT` (`oer_espressif_staged_layout::Layout`)
/// with its compile-time check, from its facts and the default CPU0 task
/// stack of its stack policy.
pub fn layout(facts: &Facts, cpu0_task_stack_bytes: u32) -> Result<String> {
    let missing = |what: &str| format!("{}: a staged layout needs {what}", facts.id);
    let memory = facts.memory.as_ref().ok_or_else(|| missing("`[memory]`"))?;
    let psram = memory.psram.ok_or_else(|| missing("the module's PSRAM"))?;
    let retained = memory
        .retained
        .ok_or_else(|| missing("`[memory] retained`"))?;
    let chain = facts
        .boot_chain
        .as_ref()
        .ok_or_else(|| missing("`[boot-chain]`"))?;
    let staged = facts.staged.as_ref().ok_or_else(|| missing("`[staged]`"))?;
    let interrupts = facts
        .interrupts
        .as_ref()
        .ok_or_else(|| missing("`[interrupts]`"))?;
    let rom = facts.rom.as_ref().ok_or_else(|| missing("`[rom]`"))?;
    let harts = u32::try_from(interrupts.harts.len()).map_err(|_| missing("fewer harts"))?;
    let mut text = String::new();
    let _ = write!(
        text,
        "// Generated by `oer_espressif_facts::generate::layout` from the facts of\n\
         // `{id}` (its layers from the ISA to the board) and the chip's stack\n\
         // policy; edit those, not this.\n\n\
         /// The staged-boot layout of `{id}` on {board}.\n\
         pub const LAYOUT: oer_espressif_staged_layout::Layout = oer_espressif_staged_layout::Layout {{\n\
         \x20   sram: {sram},\n\
         \x20   second_stage_loader_start: {loader:#010x},\n\
         \x20   flash_xip: {flash_xip},\n\
         \x20   psram: {psram},\n\
         \x20   bootstrap_psram_bytes: {probe:#x},\n\
         \x20   mmu_page_bytes: {page:#x},\n\
         \x20   image_segment_header_bytes: {header:#x},\n\
         \x20   handoff_sram_margin_bytes: {margin:#x},\n\
         \x20   retained: {retained},\n\
         \x20   retained_reserved_tail: {tail},\n\
         \x20   cpu0_task_stack_bytes: {task:#x},\n\
         \x20   irq_stack_bytes: {irq:#x},\n\
         \x20   harts: {harts},\n\
         \x20   flash_tuning_reference_bytes: {tuning:#x},\n\
         \x20   rom_script: {script:?},\n\
         }};\n\n\
         const _: () = LAYOUT.check();\n",
        id = facts.id,
        board = facts
            .board
            .as_ref()
            .map_or_else(|| "its module".to_string(), |board| board.name.clone()),
        sram = region(memory.sram),
        loader = chain.second_stage_loader_start,
        flash_xip = region(memory.flash_xip),
        psram = region(psram),
        probe = staged.bootstrap_psram_bytes,
        page = staged.mmu_page_bytes,
        header = staged.image_segment_header_bytes,
        margin = staged.handoff_sram_margin_bytes,
        retained = region(retained),
        tail = chain.retained_reserved_tail,
        task = cpu0_task_stack_bytes,
        irq = interrupts.irq_stack_bytes,
        tuning = staged.flash_tuning_reference_bytes,
        script = rom.linker_script,
    );
    Ok(text)
}

/// The CPU lines and vector tables of a chip's harts, as the staged runtime
/// generates its entries and tables from them.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Vectors {
    /// Lines `0..lines`; every line but 0 has an entry.
    pub lines: u32,
    /// The first line a peripheral source may be routed to.
    pub first_source_line: u32,
    /// The levels a line can hold: `1..=levels`.
    pub levels: u32,
    /// The harts, `0..harts`: each has its table, one after another.
    pub harts: u32,
    /// The words of one hart's table, which is aligned to its size.
    pub slots: u32,
}

impl Vectors {
    /// The vectors of `facts`' interrupt contract. The harts are numbered
    /// from 0 without a gap, since the tables follow one another by hart.
    pub fn of(facts: &Facts) -> Result<Self> {
        let interrupts = facts
            .interrupts
            .as_ref()
            .ok_or_else(|| format!("{}: the vectors need `[interrupts]`", facts.id))?;
        let harts = u32::try_from(interrupts.harts.len()).unwrap_or(u32::MAX);
        if !interrupts.harts.iter().copied().eq(0..harts) {
            return Err(format!("{}: the harts must be 0 to n - 1", facts.id).into());
        }
        Ok(Self {
            lines: interrupts.lines,
            first_source_line: interrupts.first_source_line,
            levels: interrupts.levels,
            harts,
            slots: interrupts.vector_table_hart_slots,
        })
    }

    /// The symbol of the entry of `line` on `hart`.
    pub fn entry(hart: u32, line: u32) -> String {
        format!("_runtime_irq_h{hart}_l{line}")
    }

    /// The handler the entry of `line` on `hart` calls: the interrupt table's
    /// handler of the entry bound to that line, else the runtime's stop.
    pub fn handler(hart: u32, line: u32) -> String {
        format!("__oer_interrupt_h{hart}_l{line}")
    }

    fn entries(&self) -> impl Iterator<Item = (u32, u32)> + '_ {
        (0..self.harts).flat_map(move |hart| (1..self.lines).map(move |line| (hart, line)))
    }

    /// The assembler macros the runtime's `vectors.s` invokes:
    /// `RUNTIME_IRQ_ENTRIES`, one `IRQ_ENTRY hart, line` (the runtime's macro)
    /// for every line but 0 of every hart, and `RUNTIME_VECTOR_TABLES`, each
    /// hart's table of `slots` words from a boundary of its size: zero for
    /// line 0 (exceptions enter through `mtvec`) and for the words past the
    /// lines, the line's entry for every other.
    pub fn assembly(&self) -> String {
        let mut text = String::from(
            "    // Generated by `oer_espressif_facts::generate::Vectors` from the\n\
             \x20   // chip facts' interrupt contract; edit those, not this.\n\
             \x20   .macro RUNTIME_IRQ_ENTRIES\n",
        );
        for (hart, line) in self.entries() {
            let _ = writeln!(text, "    IRQ_ENTRY {hart}, {line}");
        }
        text.push_str("    .endm\n\n    .macro RUNTIME_VECTOR_TABLES\n");
        for hart in 0..self.harts {
            let _ = writeln!(text, "    .balign {}", self.slots * 4);
            text.push_str("    .word 0\n");
            for line in 1..self.lines {
                let _ = writeln!(text, "    .word {}", Self::entry(hart, line));
            }
            let _ = writeln!(text, "    .fill {}, 4, 0", self.slots - self.lines);
        }
        text.push_str("    .endm\n");
        text
    }

    /// The runtime linker script's defaults: every line's handler is the
    /// runtime's unhandled-interrupt stop unless the image's interrupt table
    /// defines it.
    pub fn linker_defaults(&self) -> String {
        let mut text = String::from(
            "/* Generated by `oer_espressif_facts::generate::Vectors` from the chip\n   \
             facts' interrupt contract; edit those, not this. */\n",
        );
        for (hart, line) in self.entries() {
            let _ = writeln!(
                text,
                "PROVIDE({} = oer_unhandled_interrupt);",
                Self::handler(hart, line)
            );
        }
        text
    }

    /// The runtime's Rust constants: the interrupt table's `LINES`, the
    /// harts with an interrupt stack and the words of one hart's table.
    pub fn rust(&self) -> Result<String> {
        let byte = |value: u32, what: &str| {
            u8::try_from(value).map_err(|_| format!("the {what} do not fit a byte"))
        };
        Ok(format!(
            "// Generated by `oer_espressif_facts::generate::Vectors` from the chip\n\
             // facts' interrupt contract; edit those, not this.\n\n\
             /// The CPU lines of the chip's CLIC: peripheral sources route to\n\
             /// lines {first} to {last}, a line holds levels 1 to {levels}, on harts 0 to {last_hart}.\n\
             pub const LINES: oer_interrupt_table::Lines = oer_interrupt_table::Lines {{\n\
             \x20   first: {first},\n\
             \x20   count: {lines},\n\
             \x20   levels: {levels},\n\
             \x20   harts: {harts},\n\
             }};\n\n\
             /// The harts with an interrupt stack and a vector table.\n\
             pub const HARTS: usize = {harts};\n\n\
             /// The words of one hart's vector table in `_runtime_mtvt`, the table's\n\
             /// alignment in words; lines 0 to {last} have their word.\n\
             pub const VECTOR_TABLE_WORDS: usize = {slots};\n",
            first = byte(self.first_source_line, "first line")?,
            last = self.lines - 1,
            lines = byte(self.lines, "lines")?,
            levels = byte(self.levels, "levels")?,
            harts = byte(self.harts, "harts")?,
            last_hart = self.harts.saturating_sub(1),
            slots = self.slots,
        ))
    }
}

/// The tracked facts of chip `id` ([`crate::tracked`]) and the files they
/// resolve from, relative to the repository root: what a build script
/// generates from and reruns on.
pub fn tracked(id: &str) -> Result<(Facts, Vec<String>)> {
    let layers = crate::load(&mut crate::tracked::Tracked, id)?;
    let top = layers.top().to_string();
    let mut table = layers.table;
    for registry in crate::REGISTRY {
        table.remove(*registry);
    }
    Ok((Facts::from_table(id, &top, table)?, layers.files))
}

/// The generated `LAYOUT` of the tracked chip `id`, from its facts and its
/// stack policy's default task stack, and the files it reads.
pub fn tracked_layout(id: &str) -> Result<(String, Vec<String>)> {
    let (facts, mut files) = tracked(id)?;
    let policy = format!("{}/stack.toml", crate::platform_dir(id));
    let text = crate::tracked::text(&policy).ok_or_else(|| format!("{policy} is not tracked"))?;
    let layout = layout(&facts, default_cpu0_task_stack_bytes(text)?)?;
    files.push(policy);
    Ok((layout, files))
}

/// The names of a line family, for tests and tools: every entry of every
/// hart, hart by hart.
pub fn entry_symbols(vectors: &Vectors) -> Vec<String> {
    vectors
        .entries()
        .map(|(hart, line)| Vectors::entry(hart, line))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tests::tracked;

    #[test]
    fn the_vectors_follow_the_chip_s_lines_and_harts() {
        let s31 = Vectors::of(&tracked("esp32s31")).expect("vectors");
        assert_eq!((s31.lines, s31.harts, s31.slots), (48, 2, 64));
        let assembly = s31.assembly();
        let entries: Vec<&str> = assembly
            .lines()
            .filter_map(|line| line.trim().strip_prefix("IRQ_ENTRY "))
            .collect();
        assert_eq!(entries.len(), 2 * 47);
        assert_eq!(
            (entries[0], entries[46], entries[47]),
            ("0, 1", "0, 47", "1, 1")
        );
        // Each table: line 0's zero word, 47 entries, 16 words past the lines.
        let words = assembly
            .lines()
            .filter(|line| line.contains(".word"))
            .count();
        assert_eq!(words, 2 * 48);
        assert_eq!(assembly.matches(".fill 16, 4, 0").count(), 2);
        assert_eq!(assembly.matches(".balign 256").count(), 2);
        assert!(!assembly.contains('{') && !assembly.contains('}'));
        // The same facts give the same text.
        let again = Vectors::of(&tracked("esp32s31")).expect("vectors");
        assert_eq!(
            (again.assembly(), again.linker_defaults(), again.rust().ok()),
            (s31.assembly(), s31.linker_defaults(), s31.rust().ok())
        );
    }

    #[test]
    fn every_line_of_every_hart_has_its_default_handler() {
        let vectors = Vectors {
            lines: 4,
            first_source_line: 2,
            levels: 2,
            harts: 2,
            slots: 8,
        };
        assert_eq!(
            vectors
                .linker_defaults()
                .lines()
                .skip(2)
                .collect::<Vec<_>>(),
            [
                "PROVIDE(__oer_interrupt_h0_l1 = oer_unhandled_interrupt);",
                "PROVIDE(__oer_interrupt_h0_l2 = oer_unhandled_interrupt);",
                "PROVIDE(__oer_interrupt_h0_l3 = oer_unhandled_interrupt);",
                "PROVIDE(__oer_interrupt_h1_l1 = oer_unhandled_interrupt);",
                "PROVIDE(__oer_interrupt_h1_l2 = oer_unhandled_interrupt);",
                "PROVIDE(__oer_interrupt_h1_l3 = oer_unhandled_interrupt);",
            ]
        );
        assert_eq!(
            entry_symbols(&vectors),
            [
                "_runtime_irq_h0_l1",
                "_runtime_irq_h0_l2",
                "_runtime_irq_h0_l3",
                "_runtime_irq_h1_l1",
                "_runtime_irq_h1_l2",
                "_runtime_irq_h1_l3",
            ]
        );
        let rust = vectors.rust().expect("fits");
        assert!(rust.contains("first: 2,\n    count: 4,\n    levels: 2,\n    harts: 2,"));
        assert!(rust.contains("pub const VECTOR_TABLE_WORDS: usize = 8;"));
    }

    #[test]
    fn the_layout_is_the_facts_and_the_stack_policy_s_default() {
        let facts = tracked("esp32s31");
        let layout = layout(&facts, 0x3_0000).expect("a staged layout");
        for field in [
            "sram: oer_espressif_staged_layout::Region::new(0x2f000000, 0x0007afc0),",
            "second_stage_loader_start: 0x2f06cfb0,",
            "psram: oer_espressif_staged_layout::Region::new(0x50000000, 0x01000000),",
            "retained: oer_espressif_staged_layout::Region::new(0x2e000000, 0x00008000),",
            "retained_reserved_tail: 24,",
            "cpu0_task_stack_bytes: 0x30000,",
            "irq_stack_bytes: 0x8000,",
            "harts: 2,",
            "flash_tuning_reference_bytes: 0x10000,",
            "mmu_page_bytes: 0x10000,",
            "rom_script: \"rom/esp32s31-eco0.x\",",
        ] {
            assert!(layout.contains(field), "{field}\n{layout}");
        }
        assert!(layout.contains("const _: () = LAYOUT.check();"));
        // The same facts give the same text.
        assert_eq!(layout, super::layout(&facts, 0x3_0000).expect("again"));
        assert!(
            super::layout(&facts, 0x4_0000)
                .expect("bigger")
                .contains("0x40000,")
        );

        let mut bare = facts.clone();
        bare.boot_chain = None;
        assert!(
            super::layout(&bare, 0x3_0000)
                .expect_err("no boot chain")
                .to_string()
                .contains("`[boot-chain]`")
        );
    }

    #[test]
    fn the_default_task_stack_is_the_chip_policy_s() {
        for id in tracked_ids() {
            let policy = crate::tracked::text(&format!("chips/{id}/platform/stack.toml"))
                .expect("a tracked chip stack policy");
            assert_eq!(
                default_cpu0_task_stack_bytes(policy).expect("named"),
                0x3_0000
            );
        }
        for policy in [
            "schema = 6",
            "default_cpu0_task_stack_bytes = 0",
            "default_cpu0_task_stack_bytes = 17",
            "default_cpu0_task_stack_bytes = -16",
            "default_cpu0_task_stack_bytes = 'big'",
        ] {
            assert!(default_cpu0_task_stack_bytes(policy).is_err(), "{policy}");
        }
    }

    fn tracked_ids() -> Vec<&'static str> {
        crate::tracked::ids()
    }

    #[test]
    fn vectors_need_harts_numbered_from_zero() {
        let mut facts = tracked("esp32s31");
        facts.interrupts.as_mut().expect("interrupts").harts = alloc::vec![1];
        assert!(Vectors::of(&facts).is_err());
    }
}
