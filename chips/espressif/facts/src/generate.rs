//! The sources a build generates from the facts, where a person writing them
//! by hand could err: a chip's `LAYOUT` and ROM linker script (its layout
//! crate's build script),
//! and the vector table, the per-line entries, the line → handler defaults
//! and the CPU lines of the interrupt table (the staged runtime's build
//! script). Each generator is a pure function of the facts, so the same facts
//! give the same text.

use alloc::{
    format,
    string::{String, ToString},
    vec::Vec,
};
use core::fmt::Write;

use crate::{Facts, Region, Result, Rom};

mod stacks;

/// The linker assignments for exactly the ROM functions in the facts.
/// No vendor script or libc symbols are included implicitly.
pub fn rom_script(rom: &Rom) -> Result<String> {
    rom.validate_functions()?;
    let mut text = String::from(
        "/* Generated by `oer_espressif_facts::generate::rom_script`; edit the ROM facts. */\n",
    );
    for function in &rom.functions {
        let _ = writeln!(
            text,
            "/* {} */\n{} = {:#010x};",
            function.source, function.name, function.address
        );
    }
    Ok(text)
}

/// Default task allocations indexed by every hart in the chip geometry.
/// Zero is explicit storage for a contained hart.
pub fn default_task_stack_bytes(policy: &str, harts: u32) -> Result<Vec<u32>> {
    let table: toml::Table =
        toml::from_str(policy).map_err(|error| format!("the chip's stack policy: {error}"))?;
    let defaults = table
        .get("default_task_stack_bytes")
        .and_then(toml::Value::as_table)
        .ok_or("the chip's stack policy needs `default_task_stack_bytes` per hart")?;
    if defaults.len() != harts as usize {
        return Err("task defaults must name every hart exactly once".into());
    }
    (0..harts)
        .map(|hart| {
            defaults
                .get(&hart.to_string())
                .and_then(toml::Value::as_integer)
                .and_then(|bytes| u32::try_from(bytes).ok())
                .filter(|bytes| bytes % 16 == 0)
                .ok_or_else(|| {
                    format!("hart {hart}'s task default must be a u32 aligned to 16 bytes").into()
                })
        })
        .collect()
}

fn region(region: Region) -> String {
    format!(
        "const {{ oer_espressif_staged_layout::Region::new({:#010x}, {:#010x}).expect(\"region end fits u32\") }}",
        region.origin, region.length
    )
}

/// The Rust source of a chip's `LAYOUT` (`oer_espressif_staged_layout::Layout`)
/// with its compile-time check, from its facts and the default per-hart task
/// stack of its stack policy.
pub fn layout(facts: &Facts, task_stack_bytes: &[u32]) -> Result<String> {
    let missing = |what: &str| format!("{}: a staged layout needs {what}", facts.id);
    let memory = facts.memory.as_ref().ok_or_else(|| missing("`[memory]`"))?;
    let psram = memory.psram.ok_or_else(|| missing("the module's PSRAM"))?;
    let retained = memory
        .retained
        .ok_or_else(|| missing("`[memory] retained`"))?;
    let chain = facts
        .boot_chain
        .as_ref()
        .ok_or_else(|| missing("`[boot-chain]`"))?;
    let staged = facts.staged.as_ref().ok_or_else(|| missing("`[staged]`"))?;
    let interrupts = facts
        .interrupts
        .as_ref()
        .ok_or_else(|| missing("`[interrupts]`"))?;
    let rom = facts.rom.as_ref().ok_or_else(|| missing("`[rom]`"))?;
    let harts = u32::try_from(interrupts.harts.len()).map_err(|_| missing("fewer harts"))?;
    if task_stack_bytes.len() != harts as usize
        || task_stack_bytes
            .get(interrupts.boot_hart as usize)
            .is_none_or(|bytes| *bytes == 0)
    {
        return Err("task defaults need every hart and a nonempty boot stack".into());
    }
    let mut text = String::new();
    let _ = write!(
        text,
        "// Generated by `oer_espressif_facts::generate::layout` from the facts of\n\
         // `{id}` (its layers from the ISA to the board) and the chip's stack\n\
         // policy; edit those, not this.\n\n\
         /// The staged-boot layout of `{id}` on {board}.\n\
         pub const LAYOUT: oer_espressif_staged_layout::Layout = oer_espressif_staged_layout::Layout {{\n\
         \x20   sram: {sram},\n\
         \x20   second_stage_loader_start: {loader:#010x},\n\
         \x20   flash_xip: {flash_xip},\n\
         \x20   psram: {psram},\n\
         \x20   bootstrap_psram_bytes: {probe:#x},\n\
         \x20   mmu_page_bytes: {page:#x},\n\
         \x20   image_segment_header_bytes: {header:#x},\n\
         \x20   handoff_sram_margin_bytes: {margin:#x},\n\
         \x20   retained: {retained},\n\
         \x20   retained_reserved_tail: {tail},\n\
         \x20   task_stack_bytes: &{task:?},\n\
         \x20   irq_stack_bytes: {irq:#x},\n\
         \x20   harts: {harts},\n\
         \x20   boot_hart: {boot_hart},\n\
         \x20   flash_tuning_reference_bytes: {tuning:#x},\n\
         \x20   rom_script: {script:?},\n\
         }};\n\n\
         const _: () = LAYOUT.check();\n\
         const _: () = assert!(LAYOUT.boot_hart as usize == oer_espressif_staged_layout::boot::BOOT_HART);\n",
        id = facts.id,
        board = facts
            .board
            .as_ref()
            .map_or_else(|| "its module".to_string(), |board| board.name.clone()),
        sram = region(memory.sram),
        loader = chain.second_stage_loader_start,
        flash_xip = region(memory.flash_xip),
        psram = region(psram),
        probe = staged.bootstrap_psram_bytes,
        page = staged.mmu_page_bytes,
        header = staged.image_segment_header_bytes,
        margin = staged.handoff_sram_margin_bytes,
        retained = region(retained),
        tail = chain.retained_reserved_tail,
        task = task_stack_bytes,
        boot_hart = interrupts.boot_hart,
        irq = interrupts.irq_stack_bytes,
        tuning = staged.flash_tuning_reference_bytes,
        script = rom.linker_script,
    );
    Ok(text)
}

/// The CPU lines and vector tables of a chip's harts, as the staged runtime
/// generates its entries and tables from them.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Vectors {
    /// Lines `0..lines`; every line but 0 has an entry.
    pub lines: u32,
    /// The first line a peripheral source may be routed to.
    pub first_source_line: u32,
    /// The levels a line can hold: `1..=levels`.
    pub levels: u32,
    /// Implemented CLIC control bits and the selected MNLBITS.
    pub control_bits: u8,
    pub level_bits: u8,
    pub tie_break: crate::TieBreak,
    /// The harts, `0..harts`: each has its table, one after another.
    pub harts: u32,
    pub boot_hart: u32,
    /// The words of one hart's table, which is aligned to its size.
    pub slots: u32,
}

impl Vectors {
    /// The vectors of `facts`' interrupt contract. The harts are numbered
    /// from 0 without a gap, since the tables follow one another by hart.
    pub fn of(facts: &Facts) -> Result<Self> {
        let interrupts = facts
            .interrupts
            .as_ref()
            .ok_or_else(|| format!("{}: the vectors need `[interrupts]`", facts.id))?;
        interrupts.validate()?;
        let harts = u32::try_from(interrupts.harts.len()).map_err(|_| "too many HP harts")?;
        if !interrupts.harts.iter().copied().eq(0..harts) {
            return Err(format!("{}: the harts must be 0 to n - 1", facts.id).into());
        }
        Ok(Self {
            lines: interrupts.lines,
            first_source_line: interrupts.first_source_line,
            levels: interrupts.levels()?,
            control_bits: interrupts.control_bits,
            level_bits: interrupts.level_bits,
            tie_break: interrupts.tie_break,
            harts,
            boot_hart: interrupts.boot_hart,
            slots: interrupts.vector_table_hart_slots,
        })
    }

    /// The symbol of the entry of `line` on `hart`.
    pub fn entry(hart: u32, line: u32) -> String {
        format!("_runtime_irq_h{hart}_l{line}")
    }

    /// The handler the entry of `line` on `hart` calls: the interrupt table's
    /// handler of the entry bound to that line, else the runtime's stop.
    pub fn handler(hart: u32, line: u32) -> String {
        format!("__oer_interrupt_h{hart}_l{line}")
    }

    fn entries(&self) -> impl Iterator<Item = (u32, u32)> + '_ {
        (0..self.harts).flat_map(move |hart| (1..self.lines).map(move |line| (hart, line)))
    }

    /// Assembly entry instantiations and boot-stack operands. Vector data
    /// is emitted separately as typed Rust; secondary entries are unreferenced
    /// containment stubs, with no launcher or Rust admission path.
    pub fn assembly(&self) -> String {
        let mut text = String::from("    // Generated from the chip facts' interrupt contract.\n");
        for (kind, suffix) in [
            ("TASK_BOTTOM", "task_stack_bottom"),
            ("TASK_TOP", "task_stack_top"),
            ("IRQ_TOP", "irq_stack_top"),
        ] {
            let _ = writeln!(
                text,
                "    .macro RUNTIME_BOOT_{kind} reg\n    la \\reg, __runtime_cpu{}_{suffix}\n    .endm",
                self.boot_hart
            );
        }
        text.push_str("    .macro RUNTIME_IRQ_ENTRIES\n");
        for (hart, line) in self.entries() {
            let _ = writeln!(text, "    IRQ_ENTRY {hart}, {line}");
        }
        text.push_str("    .endm\n");
        for hart in (0..self.harts).filter(|hart| *hart != self.boot_hart) {
            let _ = writeln!(
                text,
                "    .section .text.secondary._runtime_start_h{hart}, \"ax\", @progbits\n    .balign 4\n    .global _runtime_start_h{hart}\n    .type _runtime_start_h{hart}, @function\n_runtime_start_h{hart}:\n    csrci mstatus, {{mie}}\n    // Every entrant parks: no launcher or admission path is linked.\n    // Touch no stack or data.\n99:\n    j 99b\n    .size _runtime_start_h{hart}, . - _runtime_start_h{hart}"
            );
        }
        text
    }

    /// Declarations expanded inside the runtime's one existing extern block.
    /// Each entry is an opaque, immutable zero-sized address marker. Rust
    /// cannot call it as an ordinary function and reading it touches no code.
    pub fn vector_markers(&self) -> String {
        let mut text = String::from(
            "// Generated from the chip interrupt geometry.\nmacro_rules! vector_markers { () => {\n",
        );
        for (hart, line) in self.entries() {
            let _ = writeln!(
                text,
                "pub(crate) safe static {}: crate::stacks::VectorEntry;",
                Self::entry(hart, line)
            );
        }
        text.push_str("}; }\n");
        text
    }

    /// Typed, per-hart MTVT rows. Optional references have the pointer's
    /// representation with a zero niche, preserving the hardware table words.
    /// One placement attribute covers the entire table, independent of hart
    /// cardinality; trap assembly exports its address through a sym operand.
    pub fn vector_tables(&self) -> String {
        let mut text = format!(
            "// Generated from the chip interrupt geometry.\n\
             #[repr(C)]\n\
             pub(crate) struct VectorEntry([u8; 0]);\n\
             #[repr(C, align({alignment}))]\n\
             struct VectorTable([Option<&'static VectorEntry>; VECTOR_TABLE_WORDS]);\n\
             const _: () = {{\n\
             assert!(core::mem::size_of::<VectorEntry>() == 0);\n\
             assert!(core::mem::size_of::<Option<&VectorEntry>>() == 4);\n\
             assert!(core::mem::size_of::<VectorTable>() == VECTOR_TABLE_WORDS * 4);\n\
             }};\n\
             #[used]\n\
             #[allow(unsafe_code, reason = \"the runtime owns MTVT placement\")]\n\
             // SAFETY: the linker reserves this immutable aligned table in .isr.text.\n\
             // _runtime_start copies it from __runtime_isr_load_start into SRAM\n\
             // before installing its vector CSRs or admitting runtime dispatch.\n\
             #[unsafe(link_section = \".trap.mtvt\")]\n\
             static MTVT: [VectorTable; HARTS] = [\n",
            alignment = self.slots * 4,
        );
        for hart in 0..self.harts {
            text.push_str("VectorTable([None,\n");
            for line in 1..self.slots {
                if line < self.lines {
                    let _ = writeln!(text, "Some(&crate::layout::{}),", Self::entry(hart, line));
                } else {
                    text.push_str("None,\n");
                }
            }
            text.push_str("]),\n");
        }
        text.push_str("];\n");
        text
    }

    /// The runtime linker script's defaults: every line's handler is the
    /// runtime's unhandled-interrupt stop unless the image's interrupt table
    /// defines it.
    pub fn linker_defaults(&self) -> String {
        let mut text = String::from(
            "/* Generated by `oer_espressif_facts::generate::Vectors` from the chip\n   \
             facts' interrupt contract; edit those, not this. */\n",
        );
        for (hart, line) in self.entries() {
            let _ = writeln!(
                text,
                "PROVIDE({} = oer_unhandled_interrupt);",
                Self::handler(hart, line)
            );
        }
        text
    }

    /// The runtime's Rust constants: the interrupt table's `LINES`, the
    /// harts with an interrupt stack and the words of one hart's table.
    pub fn rust(&self) -> Result<String> {
        let byte = |value: u32, what: &str| {
            u8::try_from(value).map_err(|_| format!("the {what} do not fit a byte"))
        };
        let mut rust = format!(
            "// Generated by `oer_espressif_facts::generate::Vectors` from the chip\n\
             // facts' interrupt contract; edit those, not this.\n\n\
             /// Implemented high bits of CLICINTCTL (CLICINTCTLBITS).\n\
             pub const CONTROL_BITS: u8 = {control_bits};\n\
             /// MNLBITS written by HAL.\n\
             pub const LEVEL_BITS: u8 = {level_bits};\n\
             /// Implemented arbitration-priority bits after selecting MNLBITS.\n\
             pub const PRIORITY_BITS: u8 = CONTROL_BITS - LEVEL_BITS;\n\n\
             /// The CPU lines of the chip's CLIC: peripheral sources route to\n\
             /// lines {first} to {last}, a line holds levels 1 to {levels}, on harts 0 to {last_hart}.\n\
             pub const LINES: oer_espressif_interrupt_table::Lines = oer_espressif_interrupt_table::Lines {{\n\
             \x20   first: {first},\n\
             \x20   count: {lines},\n\
             \x20   levels: {levels},\n\
             \x20   harts: {harts},\n\
             \x20   tie_break: oer_espressif_interrupt_table::TieBreak::{tie_break},\n\
             }};\n\n\
             /// The words of one hart's vector table in `_runtime_mtvt`, the table's\n\
             /// alignment in words; lines 0 to {last} have their word.\n\
             pub const VECTOR_TABLE_WORDS: usize = {slots};\n",
            tie_break = match self.tie_break {
                crate::TieBreak::HighestLine => "HighestLine",
            },
            control_bits = self.control_bits,
            level_bits = self.level_bits,
            first = byte(self.first_source_line, "first line")?,
            last = self.lines - 1,
            lines = byte(self.lines, "lines")?,
            levels = byte(self.levels, "levels")?,
            harts = byte(self.harts, "harts")?,
            last_hart = self.harts.saturating_sub(1),
            slots = self.slots,
        );
        let _ = writeln!(rust, "pub const HARTS: usize = {};", self.harts);
        let _ = writeln!(rust, "pub const BOOT_HART: u8 = {};", self.boot_hart);
        Ok(rust)
    }
}

