//! Finite receive-ring identity; the stub cannot advance into an out-of-range slot.
use super::RX_BUFFER_COUNT;
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub(super) enum RxIndex {
    Slot0,
    Slot1,
    Slot2,
    Slot3,
    Slot4,
    Slot5,
    Slot6,
    Slot7,
    Slot8,
    Slot9,
    Slot10,
    Slot11,
    Slot12,
    Slot13,
    Slot14,
    Slot15,
    Slot16,
    Slot17,
    Slot18,
    Slot19,
    Stub,
}
impl RxIndex {
    pub const fn value(self) -> u8 {
        self as u8
    }
    pub const fn from_raw(raw: u8) -> Option<Self> {
        match raw {
            0 => Some(Self::Slot0),
            1 => Some(Self::Slot1),
            2 => Some(Self::Slot2),
            3 => Some(Self::Slot3),
            4 => Some(Self::Slot4),
            5 => Some(Self::Slot5),
            6 => Some(Self::Slot6),
            7 => Some(Self::Slot7),
            8 => Some(Self::Slot8),
            9 => Some(Self::Slot9),
            10 => Some(Self::Slot10),
            11 => Some(Self::Slot11),
            12 => Some(Self::Slot12),
            13 => Some(Self::Slot13),
            14 => Some(Self::Slot14),
            15 => Some(Self::Slot15),
            16 => Some(Self::Slot16),
            17 => Some(Self::Slot17),
            18 => Some(Self::Slot18),
            19 => Some(Self::Slot19),
            20 => Some(Self::Stub),
            _ => None,
        }
    }
    pub fn next(self) -> Self {
        match self {
            Self::Slot0 => Self::Slot1,
            Self::Slot1 => Self::Slot2,
            Self::Slot2 => Self::Slot3,
            Self::Slot3 => Self::Slot4,
            Self::Slot4 => Self::Slot5,
            Self::Slot5 => Self::Slot6,
            Self::Slot6 => Self::Slot7,
            Self::Slot7 => Self::Slot8,
            Self::Slot8 => Self::Slot9,
            Self::Slot9 => Self::Slot10,
            Self::Slot10 => Self::Slot11,
            Self::Slot11 => Self::Slot12,
            Self::Slot12 => Self::Slot13,
            Self::Slot13 => Self::Slot14,
            Self::Slot14 => Self::Slot15,
            Self::Slot15 => Self::Slot16,
            Self::Slot16 => Self::Slot17,
            Self::Slot17 => Self::Slot18,
            Self::Slot18 => Self::Slot19,
            Self::Slot19 => Self::Slot0,
            Self::Stub => Self::Slot1,
        }
    }
    pub const fn select<T>(self, values: &[T; RX_BUFFER_COUNT + 1]) -> &T {
        let [
            v0,
            v1,
            v2,
            v3,
            v4,
            v5,
            v6,
            v7,
            v8,
            v9,
            v10,
            v11,
            v12,
            v13,
            v14,
            v15,
            v16,
            v17,
            v18,
            v19,
            v20,
        ] = values;
        match self {
            Self::Slot0 => v0,
            Self::Slot1 => v1,
            Self::Slot2 => v2,
            Self::Slot3 => v3,
            Self::Slot4 => v4,
            Self::Slot5 => v5,
            Self::Slot6 => v6,
            Self::Slot7 => v7,
            Self::Slot8 => v8,
            Self::Slot9 => v9,
            Self::Slot10 => v10,
            Self::Slot11 => v11,
            Self::Slot12 => v12,
            Self::Slot13 => v13,
            Self::Slot14 => v14,
            Self::Slot15 => v15,
            Self::Slot16 => v16,
            Self::Slot17 => v17,
            Self::Slot18 => v18,
            Self::Slot19 => v19,
            Self::Stub => v20,
        }
    }
    pub const fn select_mut<T>(self, values: &mut [T; RX_BUFFER_COUNT + 1]) -> &mut T {
        let [
            v0,
            v1,
            v2,
            v3,
            v4,
            v5,
            v6,
            v7,
            v8,
            v9,
            v10,
            v11,
            v12,
            v13,
            v14,
            v15,
            v16,
            v17,
            v18,
            v19,
            v20,
        ] = values;
        match self {
            Self::Slot0 => v0,
            Self::Slot1 => v1,
            Self::Slot2 => v2,
            Self::Slot3 => v3,
            Self::Slot4 => v4,
            Self::Slot5 => v5,
            Self::Slot6 => v6,
            Self::Slot7 => v7,
            Self::Slot8 => v8,
            Self::Slot9 => v9,
            Self::Slot10 => v10,
            Self::Slot11 => v11,
            Self::Slot12 => v12,
            Self::Slot13 => v13,
            Self::Slot14 => v14,
            Self::Slot15 => v15,
            Self::Slot16 => v16,
            Self::Slot17 => v17,
            Self::Slot18 => v18,
            Self::Slot19 => v19,
            Self::Stub => v20,
        }
    }
}
